use anyhow::bail;
use clap::{Parser, Subcommand};
use mpc_rpc_api::{new_client, TssApiClient};
use std::time::{Duration, Instant};
use uuid::Uuid;

#[derive(Parser, Debug)]
#[command(version, about, long_about = "Run local MPC benchmarks")]
pub struct Command {
    #[command(subcommand)]
    pub command: BenchmarkCommand,
}

#[derive(Subcommand, Debug)]
pub enum BenchmarkCommand {
    /// Benchmark repeated distributed key generation.
    Keygen(KeygenCommand),

    /// Benchmark repeated threshold signing.
    Keysign(KeysignCommand),
}

#[derive(Parser, Debug)]
pub struct KeygenCommand {
    /// RPC server address
    #[arg(short = 'a', long = "address", default_value = "ws://127.0.0.1:8090")]
    pub address: String,

    /// Threshold
    #[arg(short = 't', long = "threshold", default_value_t = 2)]
    pub threshold: u16,

    /// Total number of parties
    #[arg(short = 'n', long = "parties", default_value_t = 3)]
    pub parties: u16,

    /// Number of keygen requests to run sequentially.
    #[arg(long = "total", default_value_t = 100)]
    pub total: u64,

    /// Prefix used for generated wallet identifiers.
    #[arg(long, default_value = "bench-keygen")]
    pub wallet_prefix: String,

    /// Print progress every N requests. Set to 0 to disable progress.
    #[arg(long, default_value_t = 10)]
    pub progress_every: u64,
}

#[derive(Parser, Debug)]
pub struct KeysignCommand {
    /// Existing wallet identifier generated by keygen.
    #[arg(short = 'r', long = "wallet-id")]
    pub wallet_id: String,

    /// RPC server address
    #[arg(short = 'a', long = "address", default_value = "ws://127.0.0.1:8090")]
    pub address: String,

    /// Threshold needed to sign the messages (T)
    #[arg(short = 't', long = "threshold", default_value_t = 2)]
    pub threshold: u16,

    /// Number of signing requests to run sequentially.
    #[arg(long = "total", default_value_t = 1000)]
    pub total: u64,

    /// Message to sign.
    #[arg(long, default_value = "hello")]
    pub message: String,

    /// Print progress every N requests. Set to 0 to disable progress.
    #[arg(long, default_value_t = 50)]
    pub progress_every: u64,
}

impl Command {
    /// Execute `benchmark` command.
    pub async fn execute(self) -> anyhow::Result<()> {
        match self.command {
            BenchmarkCommand::Keygen(command) => command.execute().await,
            BenchmarkCommand::Keysign(command) => command.execute().await,
        }
    }
}

impl KeygenCommand {
    async fn execute(self) -> anyhow::Result<()> {
        ensure_total(self.total)?;
        ensure_non_empty("wallet-prefix", &self.wallet_prefix)?;

        let client = new_client(&self.address).await?;
        let mut latencies = Vec::with_capacity(self.total as usize);
        let mut failures = Vec::new();
        let mut success = 0_u64;
        let mut fail = 0_u64;

        println!("Running {} keygen requests...", self.total);

        for run in 1..=self.total {
            let wallet_id = format!("{}-{}", self.wallet_prefix, Uuid::new_v4());
            let started = Instant::now();
            match client
                .keygen(wallet_id.clone(), self.parties, self.threshold)
                .await
            {
                Ok(_) => {
                    success += 1;
                    latencies.push(started.elapsed());
                }
                Err(err) => {
                    fail += 1;
                    push_failure(
                        &mut failures,
                        format!("run {run}, wallet {wallet_id}: {err}"),
                    );
                }
            }

            print_progress(run, self.total, success, fail, self.progress_every);
        }

        print_summary(self.total, success, fail, &latencies, failures);
        Ok(())
    }
}

impl KeysignCommand {
    async fn execute(self) -> anyhow::Result<()> {
        ensure_total(self.total)?;

        ensure_non_empty("wallet-id", &self.wallet_id)?;
        let client = new_client(&self.address).await?;

        println!(
            "Running {} signing requests for wallet {}...",
            self.total, self.wallet_id
        );

        let message = self.message.into_bytes();
        let mut latencies = Vec::with_capacity(self.total as usize);
        let mut failures = Vec::new();
        let mut success = 0_u64;
        let mut fail = 0_u64;

        for run in 1..=self.total {
            let started = Instant::now();
            match client
                .sign(self.wallet_id.clone(), self.threshold, message.clone())
                .await
            {
                Ok(_) => {
                    success += 1;
                    latencies.push(started.elapsed());
                }
                Err(err) => {
                    fail += 1;
                    push_failure(&mut failures, format!("run {run}: {err}"));
                }
            }

            print_progress(run, self.total, success, fail, self.progress_every);
        }

        print_summary(self.total, success, fail, &latencies, failures);
        Ok(())
    }
}

fn ensure_total(total: u64) -> anyhow::Result<()> {
    if total == 0 {
        bail!("--total must be greater than 0");
    }
    Ok(())
}

fn ensure_non_empty(name: &str, value: &str) -> anyhow::Result<()> {
    if value.trim().is_empty() {
        bail!("--{name} cannot be empty");
    }
    Ok(())
}

fn push_failure(failures: &mut Vec<String>, failure: String) {
    if failures.len() >= 10 {
        failures.remove(0);
    }
    failures.push(failure);
}

fn print_progress(run: u64, total: u64, success: u64, fail: u64, progress_every: u64) {
    if progress_every > 0 && run % progress_every == 0 {
        println!("progress: {run}/{total}, success={success}, fail={fail}");
    }
}

fn print_summary(
    total: u64,
    success: u64,
    fail: u64,
    latencies: &[Duration],
    failures: Vec<String>,
) {
    let stats = BenchmarkStats::from_latencies(total, success, fail, latencies);
    println!();
    println!("{}", render_summary_table(&stats));

    if !failures.is_empty() {
        println!();
        println!("Recent failures:");
        for failure in failures {
            println!("- {failure}");
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BenchmarkStats {
    pub total: u64,
    pub success: u64,
    pub fail: u64,
    pub min_ms: Option<u64>,
    pub p50_ms: Option<u64>,
    pub p95_ms: Option<u64>,
    pub p99_ms: Option<u64>,
    pub max_ms: Option<u64>,
    pub avg_ms: Option<u64>,
}

impl BenchmarkStats {
    pub fn from_latencies(total: u64, success: u64, fail: u64, latencies: &[Duration]) -> Self {
        let mut times = latencies
            .iter()
            .map(|duration| duration.as_millis() as u64)
            .collect::<Vec<_>>();
        times.sort_unstable();

        let avg_ms = if times.is_empty() {
            None
        } else {
            Some(times.iter().sum::<u64>() / times.len() as u64)
        };

        Self {
            total,
            success,
            fail,
            min_ms: times.first().copied(),
            p50_ms: percentile(&times, 50),
            p95_ms: percentile(&times, 95),
            p99_ms: percentile(&times, 99),
            max_ms: times.last().copied(),
            avg_ms,
        }
    }
}

pub fn render_summary_table(stats: &BenchmarkStats) -> String {
    let rows = [
        ("total", stats.total.to_string()),
        ("success", stats.success.to_string()),
        ("fail", stats.fail.to_string()),
        ("min", format_optional_ms(stats.min_ms)),
        ("p50", format_optional_ms(stats.p50_ms)),
        ("p95", format_optional_ms(stats.p95_ms)),
        ("p99", format_optional_ms(stats.p99_ms)),
        ("max", format_optional_ms(stats.max_ms)),
        ("avg", format_optional_ms(stats.avg_ms)),
    ];

    let mut table = String::from("+---------+-------+\n");
    table.push_str("| metric  | value |\n");
    table.push_str("+---------+-------+\n");
    for (metric, value) in rows {
        table.push_str(&format!("| {metric:<7} | {value:<5} |\n"));
    }
    table.push_str("+---------+-------+");
    table
}

fn percentile(times: &[u64], percentile: u64) -> Option<u64> {
    if times.is_empty() {
        return None;
    }

    let index = ((times.len() as u64 * percentile).div_ceil(100) - 1) as usize;
    times.get(index.min(times.len() - 1)).copied()
}

fn format_optional_ms(value: Option<u64>) -> String {
    value
        .map(|ms| format!("{ms}ms"))
        .unwrap_or_else(|| "n/a".to_owned())
}

#[cfg(test)]
mod tests {
    use super::{render_summary_table, BenchmarkCommand, BenchmarkStats, Command};
    use clap::Parser;
    use std::time::Duration;

    #[test]
    fn stats_calculates_percentiles_from_successful_latencies() {
        let latencies = [551_u64, 565, 576, 584]
            .into_iter()
            .map(Duration::from_millis)
            .collect::<Vec<_>>();

        let stats = BenchmarkStats::from_latencies(100, 100, 0, &latencies);

        assert_eq!(stats.total, 100);
        assert_eq!(stats.success, 100);
        assert_eq!(stats.fail, 0);
        assert_eq!(stats.p50_ms, Some(565));
        assert_eq!(stats.p95_ms, Some(584));
        assert_eq!(stats.p99_ms, Some(584));
    }

    #[test]
    fn table_renders_requested_summary_rows() {
        let stats = BenchmarkStats {
            total: 100,
            success: 100,
            fail: 0,
            min_ms: Some(546),
            p50_ms: Some(551),
            p95_ms: Some(565),
            p99_ms: Some(576),
            max_ms: Some(584),
            avg_ms: Some(553),
        };

        let table = render_summary_table(&stats);

        assert!(table.contains("| total   | 100   |"));
        assert!(table.contains("| success | 100   |"));
        assert!(table.contains("| fail    | 0     |"));
        assert!(table.contains("| p50     | 551ms |"));
        assert!(table.contains("| p95     | 565ms |"));
        assert!(table.contains("| p99     | 576ms |"));
    }

    #[test]
    fn parses_keygen_subcommand() {
        let command = Command::parse_from([
            "benchmark",
            "keygen",
            "--address",
            "ws://127.0.0.1:8090",
            "--total",
            "10",
        ]);

        match command.command {
            BenchmarkCommand::Keygen(keygen) => {
                assert_eq!(keygen.address, "ws://127.0.0.1:8090");
                assert_eq!(keygen.total, 10);
            }
            BenchmarkCommand::Keysign(_) => panic!("expected keygen subcommand"),
        }
    }

    #[test]
    fn parses_keysign_subcommand() {
        let command = Command::parse_from([
            "benchmark",
            "keysign",
            "--wallet-id",
            "wallet-001",
            "--total",
            "100",
        ]);

        match command.command {
            BenchmarkCommand::Keysign(keysign) => {
                assert_eq!(keysign.wallet_id, "wallet-001");
                assert_eq!(keysign.total, 100);
            }
            BenchmarkCommand::Keygen(_) => panic!("expected keysign subcommand"),
        }
    }

    #[test]
    fn keysign_requires_wallet_id() {
        let err = Command::try_parse_from(["benchmark", "keysign"]).unwrap_err();

        assert!(err.to_string().contains("wallet-id"));
    }
}
